package main

import "testing"

func TestPlural(t *testing.T) {
	cases := []struct {
		n    int
		want string
	}{
		{0, "0 файлов"}, {1, "1 файл"}, {2, "2 файла"}, {4, "4 файла"},
		{5, "5 файлов"}, {7, "7 файлов"}, {11, "11 файлов"}, {12, "12 файлов"},
		{14, "14 файлов"}, {21, "21 файл"}, {22, "22 файла"}, {25, "25 файлов"},
		{82, "82 файла"}, {100, "100 файлов"}, {101, "101 файл"}, {111, "111 файлов"},
	}
	for _, c := range cases {
		if got := plural(c.n, "файл", "файла", "файлов"); got != c.want {
			t.Errorf("plural(%d) = %q, хотели %q", c.n, got, c.want)
		}
	}
}
